//! Automated markers and file hashes; these do not prove authorship or rights.
use regex::Regex;
use sha2::{Digest, Sha256};
use std::{
    collections::BTreeMap,
    path::{Path, PathBuf},
};

fn csv_line(fields: &[String]) -> String {
    fields
        .iter()
        .map(|field| format!("\"{}\"", field.replace('"', "\"\"")))
        .collect::<Vec<_>>()
        .join(",")
        + "\r\n"
}

pub fn audit(root: &Path) -> Result<(), String> {
    let root = std::fs::canonicalize(root).map_err(|e| e.to_string())?;
    let out = root.join("target/legal-audit");
    std::fs::create_dir_all(&out).map_err(|e| e.to_string())?;
    let patterns = [
        (
            "extraction",
            r"(?i)vineflower|decompil|auto.extract|extract(?:ed|ion)|client data|vanilla data",
        ),
        ("generated", r"(?i)auto.generated|generated by|do not edit"),
        (
            "license",
            r"(?i)SPDX-License-Identifier|copyright|licensed under|license\s*[=:]",
        ),
        (
            "upstream",
            r#"(?i)https?://(?:github\.com|gitlab\.com|crates\.io)/[^\s"'<>)]{3,}"#,
        ),
    ]
    .into_iter()
    .map(|(name, pattern)| Regex::new(pattern).map(|re| (name, re)))
    .collect::<Result<Vec<_>, _>>()
    .map_err(|e| e.to_string())?;
    let mut source = String::from(
        "\u{feff}path,bytes,sha256,status,evidence_markers,next_action,review_scope\r\n",
    );
    let mut artifacts = String::from("\u{feff}path,size_bytes,review\r\n");
    let mut errors = Vec::new();
    let mut counts: BTreeMap<&str, usize> = BTreeMap::new();
    let mut artifact_count = 0usize;
    let mut dirs: Vec<PathBuf> = vec![root.clone()];
    while let Some(dir) = dirs.pop() {
        let entries = match std::fs::read_dir(&dir) {
            Ok(v) => v,
            Err(e) => {
                errors.push(serde_json::json!({"path": dir.strip_prefix(&root).unwrap_or(&dir).to_string_lossy(), "error": e.to_string()}));
                continue;
            }
        };
        for entry in entries {
            let entry = match entry {
                Ok(v) => v,
                Err(e) => {
                    errors.push(
                        serde_json::json!({"path": dir.to_string_lossy(), "error": e.to_string()}),
                    );
                    continue;
                }
            };
            let path = entry.path();
            if path.parent() == Some(out.as_path())
                && [
                    "FILE_REVIEW_CURRENT.csv",
                    "LOCAL_ARTIFACTS_INDEX.csv",
                    "FILE_REVIEW_SUMMARY.json",
                ]
                .iter()
                .any(|name| path.file_name().is_some_and(|n| n == *name))
            {
                continue;
            }
            let relative = path.strip_prefix(&root).map_err(|e| e.to_string())?;
            let rel = relative.to_string_lossy().replace('\\', "/");
            let meta = match std::fs::symlink_metadata(&path) {
                Ok(v) => v,
                Err(e) => {
                    errors.push(serde_json::json!({"path":rel,"error":e.to_string()}));
                    continue;
                }
            };
            if meta.file_type().is_symlink() {
                errors.push(serde_json::json!({"path":rel,"error":"symlink not followed"}));
                continue;
            }
            if meta.is_dir() {
                dirs.push(path);
                continue;
            }
            if !meta.is_file() {
                continue;
            }
            let parts: Vec<_> = rel.split('/').collect();
            if matches!(
                parts.first(),
                Some(&"target" | &"artifacts" | &"dist" | &"versions" | &"Paper-26.3" | &".git")
            ) || parts.contains(&"target")
            {
                artifacts.push_str(&csv_line(&[
                    rel,
                    meta.len().to_string(),
                    "metadata only; content and rights not reviewed".into(),
                ]));
                artifact_count += 1;
                continue;
            }
            let bytes = match std::fs::read(&path) {
                Ok(v) => v,
                Err(e) => {
                    errors.push(serde_json::json!({"path":rel,"error":e.to_string()}));
                    continue;
                }
            };
            let digest = format!("{:x}", Sha256::digest(&bytes));
            let mut hits = Vec::new();
            if !bytes.iter().take(4096).any(|b| *b == 0) {
                let text = String::from_utf8_lossy(&bytes);
                for (line, value) in text.lines().enumerate() {
                    for (name, regex) in &patterns {
                        if regex.is_match(value) && hits.len() < 30 {
                            hits.push(format!("{name}:{}", line + 1));
                        }
                    }
                }
            }
            let (status, action) = if rel.starts_with("RadCore/data/mc777/")
                || [
                    "RadCore/src/mc777_data.rs",
                    "RadCore/src/packet/configuration_core_tags.rs",
                    "RadCore/src/packet/configuration_static_tags.rs",
                ]
                .contains(&rel.as_str())
            {
                (
                    "NEEDS_REVIEW_SOURCE_OR_DERIVED_DATA",
                    "Trace inputs, verify rights and release inclusion; do not publish on assumption",
                )
            } else if matches!(parts.first(), Some(&"config" | &"radonfigs" | &"radons"))
                || [
                    "rad.properties",
                    "radserver.toml",
                    "radlimbo.toml",
                    "radproxy.toml",
                    "verify-jump.log",
                ]
                .contains(&parts.last().copied().unwrap_or(""))
            {
                (
                    "LOCAL_DATA_REVIEW",
                    "Preserve; exclude local state from release unless separately reviewed",
                )
            } else {
                (
                    "AUTHORSHIP_AND_RIGHTS_UNVERIFIED",
                    "Check owner/source, dependency conditions and intended release",
                )
            };
            *counts.entry(status).or_default() += 1;
            source.push_str(&csv_line(&[rel, bytes.len().to_string(), digest, status.into(), hits.join(";"), action.into(), "full-file automated text-marker scan and hash; not a legal or manual line-by-line review".into()]));
        }
    }
    let summary = serde_json::json!({"source_files_scanned":counts.values().sum::<usize>(),"source_statuses":counts,"artifact_files_metadata_only":artifact_count,"errors_or_symlinks":errors,"limitations":"Automated marker scan, not authorship verification or legal analysis; artifacts not opened, nested archives not enumerated; provenance cannot be established from absent markers."});
    std::fs::write(out.join("FILE_REVIEW_CURRENT.csv"), source).map_err(|e| e.to_string())?;
    std::fs::write(out.join("LOCAL_ARTIFACTS_INDEX.csv"), artifacts).map_err(|e| e.to_string())?;
    std::fs::write(
        out.join("FILE_REVIEW_SUMMARY.json"),
        serde_json::to_vec_pretty(&summary).map_err(|e| e.to_string())?,
    )
    .map_err(|e| e.to_string())?;
    println!(
        "Automated scan complete. Reports: {}. This is not proof of legal clearance.",
        out.display()
    );
    Ok(())
}
